// test_runner.hpp — QPlayer in-house test runner.
// Singleton registry that collects TEST()/TEST_F() cases registered via static
// initializers, then executes them with optional glob filter.
//
// Statistics tracked:
//   total           — all registered cases (after filter)
//   passed          — EXPECT_* all green, no unexpected exception
//   failed          — at least one EXPECT_* failure or unexpected exception
//   expected_fail   — EXPECTED_FAIL_TEST body had ≥1 assertion failure
//   unexpected_pass — EXPECTED_FAIL_TEST body passed every assertion (bad)
//   unexpected_error — EXPECTED_FAIL_TEST body threw a non-assertion exception
//   not_implemented — EXPECT_NOT_IMPLEMENTED caught NotImplementedError

#pragma once

#include <functional>
#include <string>
#include <vector>

namespace qplayer::test {

// Classification of a single test result.
enum class TestStatus {
    Passed,
    Failed,
    ExpectedFail,
    UnexpectedPass,
    UnexpectedError,
};

struct TestEntry {
    std::string suite;
    std::string name;
    std::function<void()> fn;
    bool expected_fail = false;  // true when registered via EXPECTED_FAIL_TEST
};

// Thrown by assertion macros to signal a soft failure (distinguishable from
// hard std::exception throws that the runner must not swallow silently).
struct AssertionFailure {
    std::string message;
};

// TestRunner singleton — see test_runner.cpp for implementation.
class TestRunner {
public:
    static TestRunner& instance();

    // Called by static initializers generated by TEST() / TEST_F().
    void register_test(const std::string& suite,
                       const std::string& name,
                       std::function<void()> fn,
                       bool expected_fail = false);

    // Run all registered tests (optionally filtered).
    // --filter=Suite.Case or glob Suite.* is parsed from argv.
    // Returns 0 if passed + expected_fail only; nonzero on any hard failure.
    int run_all(int argc, char* argv[]);

    int exit_code() const { return exit_code_; }

    // Sorted unique suite names across all registered tests. Used by
    // --list-groups and by the group-mapping completeness self-test
    // (test_framework.cpp).
    std::vector<std::string> registered_suites() const;

    // Statistics counters (public for test_framework.cpp self-check).
    int total            = 0;
    int passed           = 0;
    int failed           = 0;
    int expected_fail    = 0;
    int unexpected_pass  = 0;
    int unexpected_error = 0;
    int not_implemented  = 0;

private:
    TestRunner() = default;
    TestRunner(const TestRunner&)            = delete;
    TestRunner& operator=(const TestRunner&) = delete;

    std::vector<TestEntry> entries_;
    int exit_code_ = 0;

    // Returns true when the "Suite.Case" label matches the filter glob.
    static bool matches_filter(const std::string& label,
                               const std::string& filter);

public:
    // Execute one entry and return its classification.
    // Public so that self-tests in test_framework.cpp can build isolated
    // mini-runners without a separate class.
    TestStatus run_one(const TestEntry& entry);
};

}  // namespace qplayer::test
